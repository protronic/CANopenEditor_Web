describe('meta addresses', () => {
  it('parses and formats addresses', () => {
    expect(parseMetaAddress('0x1400')).toEqual({ index: 0x1400, sub: null });
    expect(parseMetaAddress('2110:1f')).toEqual({ index: 0x2110, sub: 0x1f });
    expect(parseMetaAddress('0x12345')).toBeNull();
    expect(formatMetaAddress({ index: 0x1400, sub: 1 })).toBe('0x1400:01');
  });

  it('resolves sub entry, object and own references', () => {
    const document = od();
    const rpdo2 = findObject(document, 0x1401)!;
    expect(resolveMetaAddress(rpdo2, rpdo2.subObjects[1])).toEqual({ index: 0x1400, sub: 1 });
    expect(resolveMetaAddress(rpdo2, null)).toEqual({ index: 0x1400, sub: null });
    const inputs = findObject(document, 0x2110)!;
    expect(resolveMetaAddress(inputs, inputs.subObjects[2])).toEqual({ index: 0x2110, sub: 1 });
    expect(resolveMetaAddress(inputs, inputs.subObjects[1])).toEqual({ index: 0x2110, sub: 1 });
    const temp2 = findObject(document, 0x2101)!;
    expect(metaAddressIn(document, temp2, null)).toEqual({ index: 0x2100, sub: 0 });
  });

  it('lists the entries using a meta entry', () => {
    const document = od();
    const users = usedBy(document, document, { index: 0x2110, sub: 1 }).map(({ object, sub }) => formatMetaAddress({ index: object.index, sub: sub?.subIndex ?? null }));
    expect(users).toEqual(['0x2110:01', '0x2110:02']);
    expect(usedBy(document, document, { index: 0x2100, sub: 0 })).toHaveLength(2);
    expect(usedBy(document, document, { index: 0x1400, sub: 1 })).toHaveLength(2);
  });
});

